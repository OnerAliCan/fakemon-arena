package fr.epitech.fakemon.core.api;

/**
 * Représente les différents résultats d'efficacité
 * d'une attaque sur un Fakemon.
 */
public enum Effectiveness {

    /**
     * Indique que l'attaque est super efficace.
     */
    SUPER_EFFECTIVE,

    /**
     * Indique que l'attaque est peu efficace.
     */
    NOT_VERY_EFFECTIVE,

    /**
     * Indique que l'attaque n'a aucun effet.
     */
    NO_EFFECT
}