package fr.epitech.fakemon.core.api;

/**
 * Représente les deux camps participant à un combat.
 * Permet de distinguer le joueur de son adversaire.
 */
public enum Side {

    /**
     * Représente le camp contrôlé par le joueur.
     */
    PLAYER,

    /**
     * Représente le camp contrôlé par l'adversaire.
     */
    OPPONENT
}